// OpenSCAD for Argos refinement: turn a design (a scan's primitive assembly, or a board) into editable OpenSCAD code,
// check code that a model wrote, and compile it to STL with the OpenSCAD WASM build (no install, runs in Node).
// Model-written code is untrusted: no file access statements, size-capped, compiled in a worker with a time limit.
//
//   scanToScad(spec)              // OpenSCAD source for a scan spec (scan.mjs sanitizeScan output)
//   checkScad(code)               // {ok, code, error}
//   await compileScad(code)       // {ok, stl, ms, error, log}
import { Worker } from 'node:worker_threads';

export const SCAD = { maxCode: 60_000, timeoutMs: 20_000, maxStl: 40 * 1024 * 1024 };

const n = (v, d = 0) => { const x = Number(v); return Number.isFinite(x) ? Math.round(x * 100) / 100 : d; };
const vec = (v, d = 0) => `[${n(v?.x, d)}, ${n(v?.y, d)}, ${n(v?.z, d)}]`;
const ident = s => 'part_' + String(s || 'part').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 30);
const comment = s => String(s || '').replace(/[\r\n*/]+/g, ' ').slice(0, 60);
const rgb = hex => {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(hex || '')); if (!m) return '[0.55, 0.57, 0.6]';
  const v = parseInt(m[1], 16); return `[${n(((v >> 16) & 255) / 255)}, ${n(((v >> 8) & 255) / 255)}, ${n((v & 255) / 255)}]`;
};

/** One primitive, centred on the origin, sized by size_mm {x, y, z} (the same conventions as twin/scan.js). */
function primitive(p) {
  const s = p.size_mm || {}, x = n(s.x, 10), y = n(s.y, 10), z = n(s.z, 10);
  const r = n(Math.min(x, y) / 2, 5);
  switch (p.shape) {
    case 'cylinder': return `scale([${x}, ${y}, ${z}]) cylinder(d = 1, h = 1, center = true, $fn = 48);`;
    case 'sphere': return `scale([${x}, ${y}, ${z}]) sphere(d = 1, $fn = 48);`;
    case 'cone': return `scale([${x}, ${y}, ${z}]) cylinder(d1 = 1, d2 = 0, h = 1, center = true, $fn = 48);`;
    case 'capsule': return `hull() { for (k = [-1, 1]) translate([0, 0, k * ${n(Math.max(z / 2 - r, 0))}]) scale([${x}, ${y}, ${n(r * 2)}]) sphere(d = 1, $fn = 16); }`;
    case 'torus': return `scale([${x}, ${y}, ${z}]) rotate_extrude($fn = 48) translate([0.375, 0]) circle(d = 0.25, $fn = 24);`;
    case 'rounded_box': {
      const rr = n(Math.min(x, y, z) * 0.15, 0.5);
      const hx = n(Math.max(x / 2 - rr, 0.005)), hy = n(Math.max(y / 2 - rr, 0.005)), hz = n(Math.max(z / 2 - rr, 0.005));
      return `hull() { for (i = [-1, 1], j = [-1, 1], k = [-1, 1]) translate([i * ${hx}, j * ${hy}, k * ${hz}]) sphere(r = ${rr}, $fn = 8); }`;
    }
    default: return `cube([${x}, ${y}, ${z}], center = true);`;
  }
}

/**
 * Editable OpenSCAD for a scan: one module per part (named after it), placed with translate/rotate, coloured.
 * @param {{name?: string, dims_mm?: object, parts: object[]}} spec
 */
export function scanToScad(spec) {
  const parts = Array.isArray(spec?.parts) ? spec.parts.slice(0, 60) : [];
  const used = new Map();
  const mods = parts.map(p => {
    let id = ident(p.name); const k = (used.get(id) || 0) + 1; used.set(id, k); if (k > 1) id = `${id}_${k}`;
    return { id, p };
  });
  const d = spec?.dims_mm || {};
  return [
    `// ${comment(spec?.name || 'Design')}: generated by Ody (Argos refinement). Units: millimetres.`,
    `// Overall size about ${n(d.w)} x ${n(d.d)} x ${n(d.h)} mm. Each part is its own module so it can be edited alone.`,
    '',
    ...mods.flatMap(({ id, p }) => [`// ${comment(p.name)}${p.label ? ` (${comment(p.label)})` : ''}, ${p.material || 'plastic'}`,
      `module ${id}() { ${primitive(p)} }`]),
    '',
    'module assembly() {',
    ...mods.map(({ id, p }) => `  color(${rgb(p.color)}) translate(${vec(p.position_mm)}) rotate(${vec(p.rotation_deg)}) ${id}();`),
    '}',
    '',
    'assembly();',
    '',
  ].join('\n');
}

// Statements that reach outside the source (files, fonts by path, imported meshes) are refused.
const FORBIDDEN = /\b(include|use)\s*<|\bimport\s*\(|\bsurface\s*\(|\bdxf_|\bparent_module\b/;
/** Validates model-written OpenSCAD. Strips markdown fences. Never throws. */
export function checkScad(code) {
  let c = String(code ?? '').replace(/^\s*```[a-z]*\s*\n?|\n?```\s*$/gi, '');
  c = c.replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f​-‏‪-‮⁦-⁩﻿]/g, '');
  if (!c.trim()) return { ok: false, code: '', error: 'empty code' };
  if (c.length > SCAD.maxCode) return { ok: false, code: '', error: `code is longer than ${SCAD.maxCode} characters` };
  if (FORBIDDEN.test(c)) return { ok: false, code: '', error: 'include, use, import and surface are not allowed (no file access)' };
  if (/\$fn\s*=\s*(\d{4,})/.test(c)) return { ok: false, code: '', error: '$fn above 999 is too slow' };
  return { ok: true, code: c, error: '' };
}

// Resolved here, so the worker finds the package whichever folder the process was started from.
const LIB = import.meta.resolve('openscad-wasm-prebuilt');
const WORKER = `
import { parentPort, workerData } from 'node:worker_threads';
const log = [];
try {
  const { createOpenSCAD } = await import(workerData.lib);
  const o = await createOpenSCAD({ noInitialRun: true, print: s => log.push(String(s)), printErr: s => log.push(String(s)) });
  const stl = await o.renderToStl(workerData.code);
  parentPort.postMessage({ ok: true, stl, log });
} catch (e) {
  parentPort.postMessage({ ok: false, log, error: (e && e.message) || '' });
}`;

/** The useful lines of OpenSCAD's log for an error (what a model needs to fix its code). */
export const scadError = log => log.filter(l => /error|warning: (?!.*localization)/i.test(l) && !/localization/i.test(l)).join('\n').slice(0, 1500)
  || 'OpenSCAD could not render this code (no geometry?).';

/** Compiles OpenSCAD to ASCII STL in a worker. Never throws. */
export async function compileScad(code, { timeoutMs = SCAD.timeoutMs } = {}) {
  const chk = checkScad(code);
  if (!chk.ok) return { ok: false, stl: '', ms: 0, error: chk.error, log: [] };
  const t0 = Date.now();
  return new Promise(resolve => {
    const w = new Worker(WORKER, { eval: true, type: 'module', workerData: { code: chk.code, lib: LIB }, resourceLimits: { maxOldGenerationSizeMb: 1024 } });
    const done = r => { clearTimeout(t); w.terminate().catch(() => {}); resolve({ ms: Date.now() - t0, ...r }); };
    const t = setTimeout(() => done({ ok: false, stl: '', error: `OpenSCAD took longer than ${timeoutMs / 1000} s`, log: [] }), timeoutMs);
    w.once('message', m => {
      const stl = typeof m.stl === 'string' ? m.stl : '';
      if (m.ok && /facet/.test(stl) && stl.length <= SCAD.maxStl) done({ ok: true, stl, error: '', log: m.log || [] });
      else done({ ok: false, stl: '', error: m.ok ? (stl.length > SCAD.maxStl ? 'the model is too large' : 'the code made no geometry') : scadError(m.log || []), log: m.log || [] });
    });
    w.once('error', e => done({ ok: false, stl: '', error: `OpenSCAD failed: ${e?.message || e}`, log: [] }));
  });
}
