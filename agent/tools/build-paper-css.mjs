// Bundles the papyrus ink kit (twin/paper/*.svg, CC0, see twin/paper/LICENSES.md) into twin/paper.css as data-URI
// custom properties (--pk-<name>), so the page server's existing /twin/*.css route serves them with no new routes.
//   node tools/build-paper-css.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
const dir = new URL('../twin/paper/', import.meta.url);
const files = (await readdir(dir)).filter(f => /^[a-z0-9-]+\.svg$/.test(f)).sort();
const enc = s => s.replace(/\s+/g, ' ').replace(/[\r\n%#"<>{}|\\^`]/g, c => '%' + c.charCodeAt(0).toString(16).toUpperCase().padStart(2, '0'));
const lines = [];
for (const f of files) {
  const svg = await readFile(new URL(f, dir), 'utf8');
  if (/<script|<foreignObject|\son[a-z]+\s*=|href\s*=\s*["']?(?:https?:|javascript:)/i.test(svg)) throw new Error(`${f}: unexpected active content`);
  lines.push(`  --pk-${f.slice(0, -4)}:url("data:image/svg+xml,${enc(svg)}");`);
}
await writeFile(new URL('../twin/paper.css', import.meta.url),
  `/* Generated by tools/build-paper-css.mjs from twin/paper/*.svg (papyrus ink kit, CC0: twin/paper/LICENSES.md). Do not edit. */\n:root{\n${lines.join('\n')}\n}\n`);
console.log(`twin/paper.css: ${files.length} motifs`);
